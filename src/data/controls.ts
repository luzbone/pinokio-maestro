export function controlsForFamily(family: ModelFamily | "*") {
  return CONTROLS.filter((c) => c.families === "*" || (family !== "*" && c.families.includes(family)));
}

export function controlById(id: string) {
  return CONTROLS.find((c) => c.id === id);
}
